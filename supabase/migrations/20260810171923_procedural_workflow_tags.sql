-- Funcoes de autorizacao e consistencia.
create or replace function public.current_user_can_manage_procedural_tags()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = auth.uid()
      and p.status_autorizacao = 'autorizado'
      and p.cargo in ('admin', 'delegado')
  );
$$;

revoke all on function public.current_user_can_manage_procedural_tags() from public;
revoke all on function public.current_user_can_manage_procedural_tags() from anon;
grant execute on function public.current_user_can_manage_procedural_tags() to authenticated;

create or replace function public.sync_inquerito_workflow_fields()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_status public.procedural_tags%rowtype;
begin
  if new.status_tag_id is null and nullif(btrim(new.situacao), '') is not null then
    select * into v_status
    from public.procedural_tags
    where scope = 'inquerito_status'
      and lower(name) = lower(btrim(new.situacao))
      and active
    limit 1;
    new.status_tag_id := v_status.id;
  elsif new.status_tag_id is not null then
    select * into v_status
    from public.procedural_tags
    where id = new.status_tag_id and scope = 'inquerito_status' and active;
    if not found then
      raise exception 'Status de procedimento invalido.' using errcode = '23514';
    end if;
    new.situacao := v_status.name;
  end if;

  new.cidade := coalesce(nullif(btrim(new.cidade), ''), nullif(btrim(new.distrito), ''));
  if not new.prazo_manual and new.data_instauracao is not null and new.prazo_dias is not null then
    new.prazo_data_final := new.data_instauracao::date + new.prazo_dias;
  end if;
  if new.prazo_data_final is not null then
    new.prazo := new.prazo_data_final;
  end if;
  return new;
end;
$$;

create or replace function public.sync_movimentacao_workflow_fields()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_status public.procedural_tags%rowtype;
begin
  new.data_protocolo := coalesce(new.data_protocolo, new.data_representacao);
  new.data_representacao := coalesce(new.data_protocolo, new.data_representacao);

  if new.status_tag_id is null and nullif(btrim(new.status), '') is not null then
    select * into v_status
    from public.procedural_tags
    where scope = 'movimentacao_status'
      and lower(name) = lower(btrim(new.status))
      and active
    limit 1;
    new.status_tag_id := v_status.id;
  elsif new.status_tag_id is not null then
    select * into v_status
    from public.procedural_tags
    where id = new.status_tag_id and scope = 'movimentacao_status' and active;
    if not found then
      raise exception 'Status de movimentacao invalido.' using errcode = '23514';
    end if;
    new.status := v_status.name;
  end if;
  return new;
end;
$$;

drop trigger if exists sync_inquerito_workflow_fields on public.inqueritos;
create trigger sync_inquerito_workflow_fields
before insert or update of status_tag_id, situacao, data_instauracao, prazo_dias, prazo_manual,
  prazo_data_final, cidade, distrito
on public.inqueritos
for each row execute function public.sync_inquerito_workflow_fields();

drop trigger if exists sync_movimentacao_workflow_fields on public.representacoes;
create trigger sync_movimentacao_workflow_fields
before insert or update of status_tag_id, status, data_protocolo, data_representacao
on public.representacoes
for each row execute function public.sync_movimentacao_workflow_fields();

create or replace function public.record_procedural_status_history()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_previous_status_tag_id uuid;
begin
  if tg_op = 'UPDATE' then
    v_previous_status_tag_id := old.status_tag_id;
  end if;
  if tg_table_name = 'inqueritos' then
    if tg_op = 'INSERT' or new.status_tag_id is distinct from old.status_tag_id then
      insert into public.procedural_status_history (
        entity_type, inquerito_id, previous_status_tag_id, status_tag_id, changed_by
      ) values (
        'inquerito', new.id,
        v_previous_status_tag_id,
        new.status_tag_id, auth.uid()
      );
    end if;
  elsif tg_table_name = 'representacoes' then
    if tg_op = 'INSERT' or new.status_tag_id is distinct from old.status_tag_id then
      insert into public.procedural_status_history (
        entity_type, representacao_id, previous_status_tag_id, status_tag_id, changed_by
      ) values (
        'movimentacao', new.id,
        v_previous_status_tag_id,
        new.status_tag_id, auth.uid()
      );
    end if;
  end if;
  return new;
end;
$$;

revoke all on function public.record_procedural_status_history() from public;
revoke all on function public.record_procedural_status_history() from anon;
revoke all on function public.record_procedural_status_history() from authenticated;

drop trigger if exists record_inquerito_status_history on public.inqueritos;
create trigger record_inquerito_status_history
after insert or update of status_tag_id on public.inqueritos
for each row
when (new.status_tag_id is not null)
execute function public.record_procedural_status_history();

drop trigger if exists record_movimentacao_status_history on public.representacoes;
create trigger record_movimentacao_status_history
after insert or update of status_tag_id on public.representacoes
for each row
when (new.status_tag_id is not null)
execute function public.record_procedural_status_history();

create or replace function public.replace_inquerito_tags(
  p_inquerito_id uuid,
  p_tag_ids uuid[] default '{}'::uuid[]
)
returns void
language plpgsql
security invoker
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'Autenticacao obrigatoria.' using errcode = '42501';
  end if;
  if not exists (select 1 from public.inqueritos i where i.id = p_inquerito_id) then
    raise exception 'Procedimento nao encontrado ou sem acesso.' using errcode = 'P0002';
  end if;
  if exists (
    select 1
    from unnest(coalesce(p_tag_ids, '{}'::uuid[])) requested(id)
    left join public.procedural_tags t on t.id = requested.id
    where t.id is null or not t.active or t.scope not in ('tipificacao', 'inquerito_geral')
  ) then
    raise exception 'Uma ou mais tags do procedimento sao invalidas.' using errcode = '22023';
  end if;

  delete from public.inquerito_tag_links where inquerito_id = p_inquerito_id;
  insert into public.inquerito_tag_links (inquerito_id, tag_id, created_by)
  select p_inquerito_id, requested.id, auth.uid()
  from (select distinct unnest(coalesce(p_tag_ids, '{}'::uuid[])) as id) requested;
end;
$$;

create or replace function public.replace_movimentacao_tags(
  p_representacao_id uuid,
  p_tag_ids uuid[] default '{}'::uuid[]
)
returns void
language plpgsql
security invoker
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'Autenticacao obrigatoria.' using errcode = '42501';
  end if;
  if not exists (select 1 from public.representacoes r where r.id = p_representacao_id) then
    raise exception 'Movimentacao nao encontrada ou sem acesso.' using errcode = 'P0002';
  end if;
  if exists (
    select 1
    from unnest(coalesce(p_tag_ids, '{}'::uuid[])) requested(id)
    left join public.procedural_tags t on t.id = requested.id
    where t.id is null or not t.active
      or t.scope not in ('movimentacao_tipo', 'prioridade', 'movimentacao_geral')
  ) then
    raise exception 'Uma ou mais tags da movimentacao sao invalidas.' using errcode = '22023';
  end if;

  delete from public.movimentacao_tag_links where representacao_id = p_representacao_id;
  insert into public.movimentacao_tag_links (representacao_id, tag_id, created_by)
  select p_representacao_id, requested.id, auth.uid()
  from (select distinct unnest(coalesce(p_tag_ids, '{}'::uuid[])) as id) requested;
end;
$$;

