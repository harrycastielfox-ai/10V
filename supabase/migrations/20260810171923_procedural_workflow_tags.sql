-- Reestrutura o fluxo de Procedimentos Policiais e Movimentacoes Processuais.
-- Mantem os campos legados para leitura de registros antigos, mas passa a
-- usar catalogos normalizados, vinculos N:N e historico de status.

create table if not exists public.procedural_tags (
  id uuid primary key default gen_random_uuid(),
  scope text not null check (
    scope in (
      'inquerito_status',
      'tipificacao',
      'inquerito_geral',
      'movimentacao_tipo',
      'movimentacao_status',
      'prioridade',
      'movimentacao_geral'
    )
  ),
  name text not null check (length(btrim(name)) between 2 and 120),
  slug text not null check (length(btrim(slug)) between 2 and 140),
  color text not null default 'cyan' check (
    color in ('cyan', 'blue', 'green', 'amber', 'red', 'purple', 'slate')
  ),
  is_system boolean not null default false,
  active boolean not null default true,
  created_by uuid references public.profiles(id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (scope, slug)
);

create unique index if not exists procedural_tags_scope_name_unique
  on public.procedural_tags (scope, lower(btrim(name)));

create index if not exists procedural_tags_active_scope_idx
  on public.procedural_tags (scope, active, name);

alter table public.inqueritos
  add column if not exists status_tag_id uuid references public.procedural_tags(id),
  add column if not exists prazo_dias integer,
  add column if not exists prazo_data_final date,
  add column if not exists prazo_manual boolean not null default false,
  add column if not exists resumo_fato text,
  add column if not exists cidade text;

alter table public.inqueritos
  drop constraint if exists inqueritos_prazo_dias_check;

alter table public.inqueritos
  add constraint inqueritos_prazo_dias_check
  check (prazo_dias is null or prazo_dias between 0 and 3650) not valid;

alter table public.representacoes
  add column if not exists status_tag_id uuid references public.procedural_tags(id),
  add column if not exists data_protocolo date,
  add column if not exists observacoes_movimentacao text;

create table if not exists public.inquerito_tag_links (
  inquerito_id uuid not null references public.inqueritos(id) on delete cascade,
  tag_id uuid not null references public.procedural_tags(id) on delete restrict,
  created_by uuid references public.profiles(id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  primary key (inquerito_id, tag_id)
);

create index if not exists inquerito_tag_links_tag_idx
  on public.inquerito_tag_links (tag_id, inquerito_id);

create table if not exists public.movimentacao_tag_links (
  representacao_id uuid not null references public.representacoes(id) on delete cascade,
  tag_id uuid not null references public.procedural_tags(id) on delete restrict,
  created_by uuid references public.profiles(id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  primary key (representacao_id, tag_id)
);

create index if not exists movimentacao_tag_links_tag_idx
  on public.movimentacao_tag_links (tag_id, representacao_id);

create table if not exists public.procedural_status_history (
  id bigint generated by default as identity primary key,
  entity_type text not null check (entity_type in ('inquerito', 'movimentacao')),
  inquerito_id uuid references public.inqueritos(id) on delete cascade,
  representacao_id uuid references public.representacoes(id) on delete cascade,
  previous_status_tag_id uuid references public.procedural_tags(id) on delete set null,
  status_tag_id uuid not null references public.procedural_tags(id) on delete restrict,
  changed_by uuid references public.profiles(id) on delete set null default auth.uid(),
  changed_at timestamptz not null default now(),
  note text,
  check (
    (entity_type = 'inquerito' and inquerito_id is not null and representacao_id is null)
    or
    (entity_type = 'movimentacao' and representacao_id is not null and inquerito_id is null)
  )
);

create index if not exists procedural_status_history_inquerito_idx
  on public.procedural_status_history (inquerito_id, changed_at desc)
  where inquerito_id is not null;

create index if not exists procedural_status_history_movimentacao_idx
  on public.procedural_status_history (representacao_id, changed_at desc)
  where representacao_id is not null;

