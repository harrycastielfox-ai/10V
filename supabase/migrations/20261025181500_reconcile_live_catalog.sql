create table if not exists private.productivity_events (
  id bigint generated by default as identity primary key,
  actor_user_id uuid not null references public.profiles(id) on delete cascade,
  entity_type text not null check (entity_type = 'inquerito'),
  entity_id uuid not null,
  action_type text not null check (
    action_type in ('cadastro', 'atualizacao', 'relatorio_enviado')
  ),
  points smallint not null default 1 check (points = 1),
  activity_date date not null,
  occurred_at timestamptz not null default now(),
  constraint productivity_events_daily_unique unique (
    actor_user_id,
    entity_type,
    entity_id,
    action_type,
    activity_date
  )
);

alter table private.productivity_events enable row level security;
revoke all on table private.productivity_events from public, anon, authenticated, service_role;

create index if not exists productivity_events_actor_occurred_idx
  on private.productivity_events (actor_user_id, occurred_at desc);

create index if not exists productivity_events_occurred_idx
  on private.productivity_events (occurred_at desc);

create or replace function private.is_yes_like(input_value text)
returns boolean
language sql
immutable
set search_path = ''
as $function$
  select lower(trim(coalesce(input_value, ''))) = any (
    array['true', 't', '1', 'sim', 's', 'yes', 'y']
  );
$function$;

revoke all on function private.is_yes_like(text)
  from public, anon, authenticated, service_role;

create or replace function private.track_inquerito_productivity()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
declare
  actor_id uuid;
  actor_function text;
  actor_status public.authorization_status;
  action_name text;
begin
  actor_id := auth.uid();
  if actor_id is null then
    return new;
  end if;

  select p.funcao_institucional, p.status_autorizacao
    into actor_function, actor_status
  from public.profiles p
  where p.id = actor_id;

  if actor_function <> 'escrivao' or actor_status <> 'autorizado' then
    return new;
  end if;

  if tg_op = 'INSERT' then
    action_name := 'cadastro';
  elsif tg_op = 'UPDATE' then
    if new.deleted_at is not null
      and old.deleted_at is distinct from new.deleted_at then
      return new;
    end if;

    if (to_jsonb(new) - 'updated_at')
      is not distinct from (to_jsonb(old) - 'updated_at') then
      return new;
    end if;

    if (
      (
        not private.is_yes_like(old.relatorio_enviado)
        and private.is_yes_like(new.relatorio_enviado)
      )
      or (
        old.data_envio_relatorio is null
        and new.data_envio_relatorio is not null
      )
    ) then
      action_name := 'relatorio_enviado';
    else
      action_name := 'atualizacao';
    end if;
  else
    return new;
  end if;

  insert into private.productivity_events (
    actor_user_id,
    entity_type,
    entity_id,
    action_type,
    points,
    activity_date,
    occurred_at
  ) values (
    actor_id,
    'inquerito',
    new.id,
    action_name,
    1,
    timezone('America/Sao_Paulo', now())::date,
    now()
  )
  on conflict (
    actor_user_id,
    entity_type,
    entity_id,
    action_type,
    activity_date
  ) do nothing;

  return new;
end;
$function$;

revoke all on function private.track_inquerito_productivity()
  from public, anon, authenticated, service_role;

create or replace function public.handle_new_user_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_function text;
begin
  v_function := nullif(btrim(new.raw_user_meta_data->>'funcao_institucional'), '');

  if v_function not in ('escrivao', 'investigador', 'agente_policia') then
    v_function := null;
  end if;

  insert into public.profiles (
    id,
    nome,
    email,
    login,
    avatar_path,
    telefone,
    funcao_institucional,
    cargo,
    status_autorizacao
  ) values (
    new.id,
    coalesce(new.raw_user_meta_data->>'nome', split_part(new.email, '@', 1)),
    new.email,
    coalesce(new.raw_user_meta_data->>'login', split_part(new.email, '@', 1)),
    null,
    nullif(btrim(new.raw_user_meta_data->>'telefone'), ''),
    v_function,
    'membro',
    'aguardando'
  )
  on conflict (id) do update
  set
    nome = excluded.nome,
    email = excluded.email,
    login = excluded.login,
    telefone = coalesce(excluded.telefone, public.profiles.telefone),
    funcao_institucional = coalesce(
      public.profiles.funcao_institucional,
      excluded.funcao_institucional
    ),
    updated_at = now();

  return new;
end;
$function$;

revoke all on function public.handle_new_user_profile()
  from public, anon, authenticated;
grant execute on function public.handle_new_user_profile() to service_role;

create or replace function public.list_escrivao_productivity(p_days integer default 30)
returns table (
  user_id uuid,
  nome text,
  avatar_path text,
  pontos bigint,
  cadastros bigint,
  atualizacoes bigint,
  relatorios_enviados bigint,
  ultima_atividade timestamptz
)
language plpgsql
security definer
set search_path = ''
as $function$
declare
  requester_status public.authorization_status;
  safe_days integer;
begin
  if auth.uid() is null then
    raise exception 'NOT_AUTHENTICATED';
  end if;

  select p.status_autorizacao
    into requester_status
  from public.profiles p
  where p.id = auth.uid();

  if requester_status is null then
    raise exception 'PROFILE_NOT_FOUND';
  end if;

  if requester_status <> 'autorizado' then
    raise exception 'REQUESTER_NOT_AUTHORIZED';
  end if;

  safe_days := greatest(1, least(coalesce(p_days, 30), 365));

  return query
  select
    p.id,
    p.nome,
    p.avatar_path,
    coalesce(sum(e.points), 0)::bigint as pontos,
    count(e.id) filter (where e.action_type = 'cadastro')::bigint as cadastros,
    count(e.id) filter (where e.action_type = 'atualizacao')::bigint as atualizacoes,
    count(e.id) filter (where e.action_type = 'relatorio_enviado')::bigint
      as relatorios_enviados,
    max(e.occurred_at) as ultima_atividade
  from public.profiles p
  left join private.productivity_events e
    on e.actor_user_id = p.id
   and e.occurred_at >= now() - make_interval(days => safe_days)
  where p.funcao_institucional = 'escrivao'
    and p.status_autorizacao = 'autorizado'
  group by p.id, p.nome, p.avatar_path
  order by
    coalesce(sum(e.points), 0) desc,
    count(e.id) filter (where e.action_type = 'relatorio_enviado') desc,
    p.nome asc;
end;
$function$;

revoke all on function public.list_escrivao_productivity(integer) from public, anon;
grant execute on function public.list_escrivao_productivity(integer)
  to authenticated, service_role;

