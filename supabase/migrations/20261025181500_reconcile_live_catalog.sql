create or replace function public.update_own_name(p_nome text)
returns void
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_nome text;
begin
  if auth.uid() is null then
    raise exception 'NOT_AUTHENTICATED';
  end if;

  v_nome := nullif(btrim(coalesce(p_nome, '')), '');

  if v_nome is null then
    raise exception 'INVALID_NAME_EMPTY';
  end if;

  if char_length(v_nome) < 2 then
    raise exception 'INVALID_NAME_TOO_SHORT';
  end if;

  if char_length(v_nome) > 120 then
    raise exception 'INVALID_NAME_TOO_LONG';
  end if;

  update public.profiles
  set nome = v_nome,
      updated_at = now()
  where id = auth.uid();

  if not found then
    raise exception 'PROFILE_NOT_FOUND';
  end if;
end;
$function$;

